#!/usr/bin/env python3
"""Paper White 2's follower shadow camera fixes: the camera setups whose buffering, near plane or actors' clip Z offset
change so the engine's oval stays under the follower's feet (docs/paperwhite2/following-pokemon.md, Camera-side fixes).

    following_camera_fixes.py [SOURCE] OUTPUT_HEADER     # writes paperwhite2/following_camera_fixes_config.h
    following_camera_fixes.py --check [SOURCE]           # only checks the file

SOURCE is res/paperwhite2/follower_camera_fixes.json (follower_camera_fixes.schema.json beside it): a setup of
res/field/cameras/defaults.json each, with whether to Z-buffer it, its near plane in units (null keeps the setup's) and
whether to scale the actors' clip Z offset by the near plane. The header's PAPERWHITE2_FOLLOWING_CAMERA_FIXES
initializer has one { setup, zBuffer, scaleOffset, zNear } a fix, zNear in fx32 or 0 for the setup's own, which
src/paperwhite2/ov036/paperwhite2_following_render.c reads. tools/paperwhite2/camera_audit.py derives the fixes. Only
the hack's build runs this (configure.py --hack).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.data import datajson  # noqa: E402

SOURCE = ROOT / "res" / "paperwhite2" / "follower_camera_fixes.json"
CAMERAS = ROOT / "res" / "field" / "cameras" / "defaults.json"
GUARD = "POKEBW2_PAPERWHITE2_FOLLOWING_CAMERA_FIXES_CONFIG_H"
FX32_ONE = 4096


def fixes(path: Path) -> list[dict]:
    """The fixes, or a datajson.DataError that says what is wrong"""
    data = datajson.load(path, datajson.load_schema(path.parent / "follower_camera_fixes.schema.json"))
    cameras = json.loads(CAMERAS.read_text())["cameras"]
    seen = set()
    for fix in data["fixes"]:
        setup = fix["setup"]
        if setup >= len(cameras):
            raise datajson.DataError(f"{datajson.label(path)}: setup {setup} isn't in {datajson.label(CAMERAS)}")
        if setup in seen:
            raise datajson.DataError(f"{datajson.label(path)}: setup {setup} is listed twice")
        seen.add(setup)
        near = fix["near"] if fix["near"] is not None else cameras[setup]["near"] / FX32_ONE
        if near * FX32_ONE >= cameras[setup]["far"]:
            raise datajson.DataError(f"{datajson.label(path)}: setup {setup}'s near plane isn't before its far plane")
        if not fix["z_buffer"] and cameras[setup]["swap_mode"] == 1 and fix["scale_offset"]:
            raise datajson.DataError(f"{datajson.label(path)}: setup {setup} is W-buffered, where the clip Z offset "
                                     "doesn't count: Z-buffer it to scale its offset")
    return sorted(data["fixes"], key=lambda fix: fix["setup"])


def header(path: Path) -> str:
    rows = []
    for fix in fixes(path):
        near = f"FX32_CONST({fix['near']})" if fix["near"] is not None else "0"
        rows.append(f"    {{ {fix['setup']}, {'TRUE' if fix['z_buffer'] else 'FALSE'}, "
                    f"{'TRUE' if fix['scale_offset'] else 'FALSE'}, {near} }}, /* {fix['zones']} */ \\")
    return "\n".join([
        f"#ifndef {GUARD}", f"#define {GUARD}", "",
        f"// Generated by tools/paperwhite2/following_camera_fixes.py from {datajson.label(path)}, edit that instead",
        "",
        f"#define PAPERWHITE2_FOLLOWING_CAMERA_FIX_COUNT {len(rows)}",
        "// Each fix's camera setup, whether it is Z-buffered, whether the actors' clip Z offset is scaled by the near",
        "// plane, and its near plane (fx32, 0 for the setup's own)",
        "#define PAPERWHITE2_FOLLOWING_CAMERA_FIXES { \\",
        *rows,
        "}",
        "", f"#endif // {GUARD}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", type=Path, nargs="*")
    parser.add_argument("--check", action="store_true", help="only check the file")
    args = parser.parse_args()
    try:
        if args.check:
            fixes(args.paths[0] if args.paths else SOURCE)
            print(f"{datajson.label(args.paths[0] if args.paths else SOURCE)} is fine")
            return
        if not args.paths:
            parser.error("give the output header")
        source, output = (args.paths if len(args.paths) == 2 else [SOURCE, args.paths[0]])
        text = header(source)
        if not output.exists() or output.read_text() != text:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(text)
    except datajson.DataError as error:
        sys.exit(f"error: {error}")


if __name__ == "__main__":
    main()
