#!/usr/bin/env python3
"""Paper White 2's HUD wedge colors: the two colors each type's wedge takes in the battle's name boxes.

    type_colors.py [SOURCE] OUTPUT_HEADER     # writes paperwhite2/type_colors_config.h
    type_colors.py --check [SOURCE]           # only checks the file

SOURCE is res/paperwhite2/type_colors.json (type_colors.schema.json beside it): for every type of generated/types.txt,
in ID order, the wedge's fill and its darker edge as 8-bit RGB, which this rounds to the DS's 5 bits an axis
(round(v * 31 / 255), as every palette of res/ is read) and writes as BGR555 into the header's two initializers,
PAPERWHITE2_TYPE_FILL_COLORS and PAPERWHITE2_TYPE_EDGE_COLORS, which
src/paperwhite2/ov168/paperwhite2_type_icons.c uses for TYPE_COLORS and TYPE_SHADES. Only the hack's build runs this
(configure.py --hack).
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.data import datajson  # noqa: E402

SOURCE = ROOT / "res" / "paperwhite2" / "type_colors.json"
GUARD = "POKEBW2_PAPERWHITE2_TYPE_COLORS_CONFIG_H"


def color555(color: list[int]) -> int:
    """An 8-bit color as the DS's BGR555 value."""
    r, g, b = (round(axis * 31 / 255) for axis in color)
    return r | g << 5 | b << 10


def tables(path: Path) -> tuple[list[int], list[int]]:
    """The fill and edge colors by type ID, or a datajson.DataError that says what is wrong."""
    data = datajson.load(path, datajson.load_schema(path.parent / "type_colors.schema.json"))
    names = datajson.names("TYPE_")
    ids = datajson.constants()
    types = data["types"]
    expected = [names[value] for value in sorted(names)]
    for name in types:
        if name not in ids or ids[name] not in names or names[ids[name]] != name:
            raise datajson.DataError(f"{datajson.label(path)}: {name} is not a type of generated/types.txt")
    missing = [name for name in expected if name not in types]
    if missing:
        raise datajson.DataError(f"{datajson.label(path)}: no colors for {', '.join(missing)}")
    order = sorted(types, key=lambda name: ids[name])
    if [ids[name] for name in order] != list(range(len(order))):
        raise datajson.DataError(f"{datajson.label(path)}: the types' IDs aren't 0 to {len(order) - 1}")
    return [color555(types[name]["fill"]) for name in order], [color555(types[name]["edge"]) for name in order]


def initializer(values: list[int]) -> str:
    rows = [values[i:i + 8] for i in range(0, len(values), 8)]
    return "{ \\\n" + " \\\n".join("    " + ", ".join(f"0x{v:04x}" for v in row) + "," for row in rows) + " \\\n}"


def header(path: Path) -> str:
    fill, edge = tables(path)
    return "\n".join([
        f"#ifndef {GUARD}", f"#define {GUARD}", "",
        f"// Generated by tools/paperwhite2/type_colors.py from {datajson.label(path)}, edit that instead",
        "",
        f"#define PAPERWHITE2_TYPE_COLOR_COUNT {len(fill)}",
        "// Each type's wedge fill and darker edge, BGR555, by type ID",
        f"#define PAPERWHITE2_TYPE_FILL_COLORS {initializer(fill)}",
        f"#define PAPERWHITE2_TYPE_EDGE_COLORS {initializer(edge)}",
        "", f"#endif // {GUARD}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", type=Path, nargs="*")
    parser.add_argument("--check", action="store_true", help="only check the file")
    args = parser.parse_args()
    try:
        if args.check:
            tables(args.paths[0] if args.paths else SOURCE)
            print(f"{datajson.label(args.paths[0] if args.paths else SOURCE)} is fine")
            return
        if not args.paths:
            parser.error("give the output header")
        source, output = (args.paths if len(args.paths) == 2 else [SOURCE, args.paths[0]])
        text = header(source)
        if not output.exists() or output.read_text() != text:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(text)
    except datajson.DataError as error:
        sys.exit(f"error: {error}")


if __name__ == "__main__":
    main()
