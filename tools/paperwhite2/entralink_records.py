#!/usr/bin/env python3
"""Paper White 2's Entralink roguelike records: the generated header of res/paperwhite2/entralink/records.json.

    entralink_records.py OUTPUT_HEADER     # writes paperwhite2/entralink_records_config.h
    entralink_records.py --check           # only checks the data

The Nightmare codex (docs/paperwhite2/design/entralink-roguelike-prototype.md, "Records") records the added species
that never enter the Pokédex ("pokedex": false in their data.json, not retired), in every form, and records.json's
special forms, each alone. The header's ENTRALINK_RECORDS_CODEX lists them for
src/paperwhite2/ov012/paperwhite2_entralink_records.c: a species as its number, a special form as
ENTRALINK_RECORDS_CODEX_KEY(species, form) with ENTRALINK_RECORDS_CODEX_SPECIAL. The save holds at most CODEX_MAX
entries (ENTRALINK_RECORDS_CODEX_MAX, include/paperwhite2/entralink_progress.h). Only the hack's build runs this.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.data import datajson, species_list  # noqa: E402

SOURCE = ROOT / "res" / "paperwhite2" / "entralink"
POKEMON = ROOT / "res" / "pokemon"
GUARD = "POKEBW2_PAPERWHITE2_ENTRALINK_RECORDS_CONFIG_H"
# The save's codex entries, and a key's parts (include/paperwhite2/entralink_records.h)
CODEX_MAX = 64
SPECIES_BITS = 10
SPECIAL = 0x8000


def nightmares(pokemon: Path = POKEMON) -> list[int]:
    """The added species with "pokedex": false that aren't retired, in ID order."""
    return [number for number in range(species_list.FIRST_ADDED, species_list.last_species() + 1)
            if (data := species_list.species_data(number, pokemon)).get("pokedex") is False
            and data.get("retired") is not True]


def form_count(number: int, pokemon: Path = POKEMON) -> int:
    return species_list.species_data(number, pokemon).get("forms", {}).get("count", 1)


def codex(directory: Path = SOURCE, pokemon: Path = POKEMON) -> list[tuple[str, int]]:
    """The codex's entries: (a name for the header's comment, the entry), or a datajson.DataError."""
    records = datajson.load(directory / "records.json", datajson.load_schema(directory / "records.schema.json"))
    constants = datajson.constants()
    entries = [(datajson.name("SPECIES_", number), number) for number in nightmares(pokemon)]
    for special in records["special_forms"]:
        number = constants[special["species"]]
        if special["form"] >= form_count(number, pokemon):
            raise datajson.DataError(f"records.json: {special['species']} has no form {special['form']} "
                                     f"(its forms: {form_count(number, pokemon)})")
        entries.append((f"{special['species']}, form {special['form']}",
                        number | special["form"] << SPECIES_BITS | SPECIAL))
    if len(entries) > CODEX_MAX:
        raise datajson.DataError(f"records.json: the codex has {len(entries)} species and special forms, more than "
                                 f"the save's {CODEX_MAX}")
    return entries


def header(directory: Path = SOURCE, pokemon: Path = POKEMON) -> str:
    entries = codex(directory, pokemon)
    rows = [f"    0x{entry:04x}, /* {name} */ \\" for name, entry in entries] or ["    0, \\"]
    return "\n".join([
        f"#ifndef {GUARD}", f"#define {GUARD}", "",
        f"// Generated by tools/paperwhite2/entralink_records.py from {datajson.label(directory / 'records.json')}",
        "// and the species' data, edit those instead", "",
        "// The Nightmare codex: its species (a number), then records.json's special forms",
        f"#define ENTRALINK_RECORDS_CODEX_COUNT {max(len(entries), 1)}",
        "#define ENTRALINK_RECORDS_CODEX { \\", *rows, "}",
        "", f"#endif // {GUARD}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("output", type=Path, nargs="?")
    parser.add_argument("--check", action="store_true", help="only check the data")
    args = parser.parse_args()
    try:
        if args.check:
            codex()
            print("records.json is fine")
            return
        if args.output is None:
            parser.error("give the output header")
        text = header()
        if not args.output.exists() or args.output.read_text() != text:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(text)
    except datajson.DataError as error_:
        sys.exit(f"error: {error_}")


if __name__ == "__main__":
    main()
