#!/usr/bin/env python3
"""Paper White 2: the Following Pokémon's scene policy, from Pokeweb's reviewed command and sound event policies.

    following_scene_policy.py EVENT_POLICY AUDIO_POLICY SYMBOLS SCENE_HEADER SOUND_HEADER

res/paperwhite2/following/event-policy.json and audio-event-policy.json are Pokeweb's policies, as its
generate_scene_policy.py read them (docs/paperwhite2/following-pokemon.md, Step 4):

- event-policy.json's `commands`: the field script commands that keep the follower (pause it) instead of recalling
  it, by opcode, each with the handler and its first bytes that Pokeweb pinned when it reviewed the command; and its
  `finishers`: the script's sub events (FieldScriptSubEvent_Register's IDs, 0 to 13) that may still run when the
  script's end cleans up.
- audio-event-policy.json's `events`: the sound events that only play music, which keep the follower, by their
  callback's address in White 2, and `pureAudioOpcodes`, the commands that start them, which must be in `commands`.

SCENE_HEADER has FOLLOWING_SAFE_COMMANDS, the sorted opcodes, and FOLLOWING_SAFE_FINISHERS, the finishers' bit mask,
for src/paperwhite2/ov036/paperwhite2_following_scene.c. SOUND_HEADER has Following_IsSoundCallback, which compares a callback with the
sound events' callbacks by their names in the decomp, resolved from SYMBOLS (config/w2_us/arm9/symbols.txt), for
src/system/event_sound.c, where those static callbacks are. Only the hack's build runs this (configure.py --hack).
"""
import argparse
import json
import re
import sys
from pathlib import Path

COMMAND_LIMIT = 0x2F3
FINISHER_LIMIT = 14
PER_LINE = 12
SYMBOL = re.compile(r"^(\S+) kind:function\([^)]*\) addr:0x([0-9a-fA-F]+)")


def fail(message):
    sys.exit(f"following_scene_policy.py: {message}")


def load_functions(path):
    """The functions of a symbols.txt by address."""
    functions = {}
    for line in Path(path).read_text().splitlines():
        match = SYMBOL.match(line)
        if match:
            functions[int(match.group(2), 16)] = match.group(1)
    return functions


def check_pinned(entry, what):
    if not entry["handler"] & 1 or len(bytes.fromhex(entry["expectedHex"])) < 4:
        fail(f"{what} {entry['name']} needs a pinned Thumb handler")


def scene_header(policy):
    commands = [entry["opcode"] for entry in policy["commands"]]
    if policy["abi"] != 1 or commands != sorted(set(commands)) or any(not 0 <= n < COMMAND_LIMIT for n in commands):
        fail("invalid command policy")
    for entry in policy["commands"]:
        check_pinned(entry, "command")
    finishers = policy["finishers"]
    indices = [entry["index"] for entry in finishers]
    if indices != sorted(set(indices)) or any(not 0 <= n < FINISHER_LIMIT for n in indices):
        fail("invalid finisher policy")
    for entry in finishers:
        check_pinned(entry, "finisher")
    names = ", ".join(entry["name"] for entry in finishers)
    lines = [
        "// Generated by tools/paperwhite2/following_scene_policy.py from res/paperwhite2/following/event-policy.json",
        "#ifndef POKEBW2_PAPERWHITE2_FOLLOWING_SCENE_POLICY_H",
        "#define POKEBW2_PAPERWHITE2_FOLLOWING_SCENE_POLICY_H",
        "",
        "#include \"types.h\"",
        "",
        f"// The script's sub events that may run at its end: {names}",
        f"#define FOLLOWING_SAFE_FINISHERS 0x{sum(1 << i for i in indices):08x}",
        "",
        "// The field script commands that keep the follower, sorted",
        "static const u16 FOLLOWING_SAFE_COMMANDS[] = {",
    ]
    for i in range(0, len(commands), PER_LINE):
        lines.append("    " + ", ".join(f"0x{n:04x}" for n in commands[i:i + PER_LINE]) + ",")
    lines += ["};", "", "#endif // POKEBW2_PAPERWHITE2_FOLLOWING_SCENE_POLICY_H", ""]
    return commands, "\n".join(lines)


def sound_header(audio, commands, functions):
    callbacks = [entry["callback"] for entry in audio["events"]]
    if audio["schemaVersion"] != 1 or callbacks != sorted(set(callbacks)) or any(not n & 1 for n in callbacks):
        fail("invalid sound event policy")
    if any(code not in commands for code in audio["pureAudioOpcodes"]):
        fail("a sound command is missing from the command policy")
    names = []
    for entry in audio["events"]:
        name = functions.get(entry["callback"] & ~1)
        if name is None:
            fail(f"no function at 0x{entry['callback'] & ~1:08x} for the sound event {entry['name']}")
        names.append(name)
    lines = [
        "// Generated by tools/paperwhite2/following_scene_policy.py from "
        "res/paperwhite2/following/audio-event-policy.json",
        "#ifndef POKEBW2_PAPERWHITE2_FOLLOWING_SOUND_POLICY_H",
        "#define POKEBW2_PAPERWHITE2_FOLLOWING_SOUND_POLICY_H",
        "",
        "#include \"types.h\"",
        "#include \"system/game_event.h\"",
        "",
        "// event_sound.c's callbacks of the sound events that keep the follower",
    ]
    lines += [f"static GameEventReturnCode {name}(GameEvent *event, u32 *state, void *data);" for name in names]
    # Comparisons, not a table: event_sound.c is a file of main, whose sections the linker script lists, and it has no
    # .rodata
    lines += ["", "static inline BOOL Following_IsSoundCallback(GameEventCallback callback) {"]
    lines.append("    return " + " ||\n           ".join(f"callback == {name}" for name in names) + ";")
    lines += ["}", "", "#endif // POKEBW2_PAPERWHITE2_FOLLOWING_SOUND_POLICY_H", ""]
    return "\n".join(lines)


def write(path, text):
    path = Path(path)
    if not path.exists() or path.read_text() != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("event_policy")
    parser.add_argument("audio_policy")
    parser.add_argument("symbols")
    parser.add_argument("scene_header")
    parser.add_argument("sound_header")
    args = parser.parse_args()
    policy = json.loads(Path(args.event_policy).read_text())
    audio = json.loads(Path(args.audio_policy).read_text())
    commands, scene = scene_header(policy)
    sound = sound_header(audio, commands, load_functions(args.symbols))
    write(args.scene_header, scene)
    write(args.sound_header, sound)


if __name__ == "__main__":
    main()
