#!/usr/bin/env python3
"""Paper White 2's custom tints: the field weathers WEATHER_CUSTOM_TINT_1 to _12, each a fog in a colour of its own.

    field_tints.py [SOURCE] OUTPUT_HEADER     # writes paperwhite2/field_tints_config.h
    field_tints.py --check [SOURCE]           # only checks the file

SOURCE is res/paperwhite2/field_tints/tints.json (tints.schema.json beside it): the tints in slot order, each a colour
as 8-bit RGB, which this rounds to the DS's 5 bits an axis (round(v * 31 / 255), as every palette of res/ is read), a
strength in percent, which becomes the fog's density at its thickest (0 to 127), and a style: flat (shift and offset 0,
every depth the same) or fog (its fog_shift and fog_offset, 8 and 32597 when left out). The header's
PAPERWHITE2_FIELD_TINTS initializes src/paperwhite2/ov036/paperwhite2_field_tint.c's FieldTint table, and there are no
more tints than include/system/zone_weather.h has WEATHER_CUSTOM_TINT_ slots. Only the hack's build runs this
(configure.py --hack).
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.data import datajson  # noqa: E402

SOURCE = ROOT / "res" / "paperwhite2" / "field_tints" / "tints.json"
WEATHER_HEADER = ROOT / "include" / "system" / "zone_weather.h"
GUARD = "POKEBW2_PAPERWHITE2_FIELD_TINTS_CONFIG_H"
# paperwhite2_field_tint.c's TINT_STYLE_*
STYLES = {"flat": 0, "fog": 1}
FOG_DENSITY_MAX = 127
DEFAULT_FOG_SHIFT = 8
DEFAULT_FOG_OFFSET = 0x7F55


def color555(color: list[int]) -> int:
    """An 8-bit color as the DS's BGR555 value."""
    r, g, b = (round(axis * 31 / 255) for axis in color)
    return r | g << 5 | b << 10


def slot_count() -> int:
    """How many WEATHER_CUSTOM_TINT_ weathers include/system/zone_weather.h has."""
    return len(re.findall(r"\bWEATHER_CUSTOM_TINT_\d+,", WEATHER_HEADER.read_text()))


def tints(path: Path) -> list[tuple[int, int, int, int, int]]:
    """Each tint's color, density, style, shift and offset, or a datajson.DataError that says what is wrong."""
    data = datajson.load(path, datajson.load_schema(path.parent / "tints.schema.json"))
    slots = slot_count()
    if len(data["tints"]) > slots:
        raise datajson.DataError(f"{datajson.label(path)}: {len(data['tints'])} tints, but "
                                 f"{datajson.label(WEATHER_HEADER)} has {slots} WEATHER_CUSTOM_TINT_ slots")
    result = []
    for i, tint in enumerate(data["tints"]):
        style = tint["style"]
        if style == "flat" and ("fog_shift" in tint or "fog_offset" in tint):
            raise datajson.DataError(f"{datajson.label(path)}: tint {i + 1} ({tint['name']}) is flat, which has no "
                                     "fog_shift or fog_offset")
        shift, offset = ((tint.get("fog_shift", DEFAULT_FOG_SHIFT), tint.get("fog_offset", DEFAULT_FOG_OFFSET))
                         if style == "fog" else (0, 0))
        result.append((color555(tint["color"]), round(tint["strength"] * FOG_DENSITY_MAX / 100), STYLES[style],
                       shift, offset))
    return result


def header(path: Path) -> str:
    rows = [f"    {{ 0x{color:04x}, {density}, {style}, {shift}, 0x{offset:04x} }}, \\"
            for color, density, style, shift, offset in tints(path)]
    return "\n".join([
        f"#ifndef {GUARD}", f"#define {GUARD}", "",
        f"// Generated by tools/paperwhite2/field_tints.py from {datajson.label(path)}, edit that instead",
        "",
        f"#define PAPERWHITE2_FIELD_TINT_COUNT {len(rows)}",
        "// Each tint's colour (BGR555), density (0 to 127), style (0 flat, 1 fog), fog shift and fog offset, by slot",
        "#define PAPERWHITE2_FIELD_TINTS { \\", *rows, "}",
        "", f"#endif // {GUARD}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", type=Path, nargs="*")
    parser.add_argument("--check", action="store_true", help="only check the file")
    args = parser.parse_args()
    try:
        if args.check:
            tints(args.paths[0] if args.paths else SOURCE)
            print(f"{datajson.label(args.paths[0] if args.paths else SOURCE)} is fine")
            return
        if not args.paths:
            parser.error("give the output header")
        source, output = (args.paths if len(args.paths) == 2 else [SOURCE, args.paths[0]])
        text = header(source)
        if not output.exists() or output.read_text() != text:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(text)
    except datajson.DataError as error:
        sys.exit(f"error: {error}")


if __name__ == "__main__":
    main()
