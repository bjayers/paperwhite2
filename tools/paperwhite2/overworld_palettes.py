#!/usr/bin/env python3
"""Paper White 2: the overworld Pokémon sheets on their species' battle palettes
(docs/paperwhite2/design/follower-palette-remap.md, section 9).

Every overworld Pokémon sheet (res/field/actors/followers/<name>/ and the walking Pokémon's pokemon/<name>/) has
its pixels as indices of a battle group's palette, the group its data.json's "palette" names:

    "palette": { "pokemon": "pidove" }              the sheet is pidove's battle indices: no sprite.pal, the
                                                    build writes res/pokemon/pidove/normal.pal as its palette
    "palette": { "opt_out": "why" }                 the sheet keeps its own sprite.pal and indices
    "palette": { "pokemon": "appletun", "map": [] } on a follower row that shows another group's sheet: the 16
                                                    battle indices of this group that the sheet's indices play

A follower row's colours at run time (its normal and shiny palettes, the follower's and a wanderer's) are those of its
own group (species and form), generated by field_actor_data.py into the follower palettes member; see palette_rows().

    overworld_palettes.py usage OUT.md          the listing of every sheet's users (followers, NPCs, ambients, the
                                                Entralink run) and the sheets that serve groups with other palettes
    overworld_palettes.py convert [--dry-run]   the one-time conversion of 2026-11-22 (overworld_palettes_convert.py)
    overworld_palettes.py remap DIR GROUP       new art in DIR (sprite.png and sprite.pal, as drawn) re-indexed onto
                                                GROUP's battle palette: DIR's sprite.png rewritten, sprite.pal removed,
                                                data.json given "palette"; prints the needs-a-look reasons

Standard library only (the build's python3).
"""
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.data.nitro_2d import color5, read_indexed_png, read_palette, write_indexed_png  # noqa: E402
from tools.paperwhite2 import palette_remap  # noqa: E402

ACTORS = ROOT / "res" / "field" / "actors"
POKEMON = ROOT / "res" / "pokemon"
OBJ_CODES = ROOT / "generated" / "obj_codes.txt"
CODE = re.compile(r"\bOBJ_CODE_[A-Z0-9_]+\b")
WALKING = re.compile(r"^OBJ_CODE_POKEMON_(?P<name>.+?)(?P<female>_FEMALE|_MALE)?(?:_FORM_(?P<form>\d+))?$")
FOLLOWER_PREFIX = "OBJ_CODE_FOLLOWER_"
WALKING_PREFIX = "OBJ_CODE_POKEMON_"
COLORS = 16


def group_name(species: str, form: int) -> str:
    """The battle group (a directory of res/pokemon) of a species constant and form: its form_<n> where it has one,
    else the species' own, as GetPokemonDataIDBase falls back."""
    name = species.removeprefix("SPECIES_").lower()
    if form and (POKEMON / name / f"form_{form}" / "normal.pal").is_file():
        return f"{name}/form_{form}"
    return name


def art_directory(group: str) -> Path:
    """Where a group's battle frames are: its own, or the species' for a palette-only form (Arceus')."""
    path = POKEMON / group
    return path if (path / "front.png").is_file() else POKEMON / group.split("/")[0]


def has_female_art(group: str) -> bool:
    return (art_directory(group) / "front_female.png").is_file()


def same_layout(a: str, b: str) -> bool:
    """Whether two groups' palettes play the same roles: one group, or forms of one species with the same art (a
    palette-only form, or a form whose frames are the base's pixel for pixel, as Genesect's drives)."""
    if a == b:
        return True
    if a.split("/")[0] != b.split("/")[0]:
        return False
    art_a, art_b = art_directory(a), art_directory(b)
    if art_a == art_b:
        return True
    return all((art_a / name).is_file() and (art_b / name).is_file() and
               read_indexed_png(art_a / name)[2] == read_indexed_png(art_b / name)[2]
               for name in ("front.png", "back.png"))


def directory(code: str) -> Path:
    name = code.removeprefix("OBJ_CODE_")
    for prefix, group in (("POKEMON_", "pokemon"), ("MODEL_", "models"), ("FOLLOWER_", "followers")):
        if name.startswith(prefix):
            return ACTORS / group / name.removeprefix(prefix).lower()
    return ACTORS / name.lower()


def obj_codes() -> list[str]:
    return [line.split()[0] for line in OBJ_CODES.read_text().splitlines() if line.startswith("OBJ_CODE_")]


class Actors:
    """The object codes' data.json files and which sheet each shows."""

    def __init__(self):
        self.codes = obj_codes()
        self.data = {}
        for code in self.codes:
            path = directory(code) / "data.json"
            if path.is_file():
                self.data[code] = json.loads(path.read_text())

    def owner(self, code: str) -> str | None:
        """The code whose sprite.png a sprite code shows."""
        data = self.data.get(code)
        if data is None or data.get("type") != "sprite":
            return None
        return data.get("sprite", code)

    def is_pokemon_sheet(self, code: str) -> bool:
        return (code.startswith(FOLLOWER_PREFIX) or code.startswith(WALKING_PREFIX)) and \
            (directory(code) / "sprite.png").is_file()

    def own_group(self, code: str) -> tuple[str, str] | None:
        """The group and sex ("m" or "f") a Pokémon code shows by itself: its follower row's, or its name's for a
        walking Pokémon."""
        data = self.data.get(code, {})
        follower = data.get("follower")
        if follower is not None:
            group = group_name(follower["species"], follower["form"])
            return group, "f" if follower["sex"] == "GENDER_FEMALE" and has_female_art(group) else "m"
        match = WALKING.match(code)
        if match:
            species = "SPECIES_" + match["name"]
            group = group_name(species, int(match["form"] or 0))
            if not (POKEMON / group / "normal.pal").is_file():
                return None
            return group, "f" if match["female"] == "_FEMALE" and has_female_art(group) else "m"
        return None

    def sheet_group(self, code: str) -> str | None:
        """The group a sheet is indexed on ("palette"."pokemon"), else the one its owner shows by itself."""
        palette = self.data.get(code, {}).get("palette", {})
        if "opt_out" in palette:
            return None
        if "pokemon" in palette:
            return palette["pokemon"]
        own = self.own_group(code)
        return own[0] if own else None


def references() -> dict[str, list[tuple[str, str]]]:
    """Every object code named outside res/field/actors: (kind, where) a code."""
    found: dict[str, list[tuple[str, str]]] = {}
    sources = [("NPC", ROOT / "res/field/events", "*.json"), ("script", ROOT / "res/field/scripts", "*.s"),
               ("ambient", ROOT / "res/paperwhite2/overworld", "*.json"),
               ("Entralink", ROOT / "res/paperwhite2/entralink", "**/*.json"), ("code", ROOT / "src", "**/*.c")]
    for kind, base, pattern in sources:
        for path in sorted(base.glob(pattern)):
            for code in CODE.findall(path.read_text(errors="replace")):
                where = (kind, path.stem)
                if where not in found.setdefault(code, []):
                    found[code].append(where)
    return found


def usage(actors: Actors) -> dict[str, dict]:
    """Per Pokémon sheet: its own group, the follower rows on it and the codes named elsewhere that show it."""
    sheets: dict[str, dict] = {}
    for code in actors.codes:
        if actors.is_pokemon_sheet(code):
            own = actors.own_group(code)
            sheets[code] = {"group": actors.sheet_group(code), "own": own, "rows": [], "uses": [],
                            "palette": actors.data[code].get("palette", {})}
    for code in actors.codes:
        owner = actors.owner(code)
        if owner not in sheets:
            continue
        follower = actors.data[code].get("follower")
        if follower is not None:
            sheets[owner]["rows"].append((code, follower, actors.data[code].get("palette", {})))
    for code, wheres in references().items():
        owner = actors.owner(code)
        if owner in sheets:
            sheets[owner]["uses"] += [(code, kind, where) for kind, where in wheres]
    return sheets


def palettes_differ(a: str, b: str) -> bool:
    return read_palette(POKEMON / a / "normal.pal") != read_palette(POKEMON / b / "normal.pal")


def write_usage(output: Path):
    actors = Actors()
    sheets = usage(actors)
    lines = ["# Overworld Pokémon sheets and their users (generated)", "",
             "Generated by `tools/paperwhite2/overworld_palettes.py usage` from `res/`; don't edit. Each row is a sheet "
             "(a code with a `sprite.png` of its own) with the battle group it is indexed on, the follower rows that "
             "show it (the follower and the wanderers pick their sprite through these rows), and the codes that show "
             "it elsewhere: zone NPCs (`res/field/events`), scripts, ambients (`res/paperwhite2/overworld`) and the "
             "Entralink run's rooms and templates. The Entralink's random rooms also show any species' walking sprite "
             "(else its follower sprite) by species. **Flags:** `opt-out` (the sheet keeps its own palette, with the "
             "reason); `mapped`: rows of another species that play the sheet through a map of their own palette; "
             "`forms`: rows of forms of one species whose palettes share the roles; `other palette`: rows of another "
             "group that nothing colours right (none should be left: the build refuses them).", ""]
    flagged = {"opt-out": [], "mapped": [], "other palette": []}
    lines += ["| sheet | indexed on | follower rows | NPCs, ambients, Entralink | flags |", "| --- | --- | --- | --- | --- |"]
    for code, sheet in sheets.items():
        groups = {}
        mapped = set()
        for row_code, follower, palette in sheet["rows"]:
            group = palette.get("pokemon") or group_name(follower["species"], follower["form"])
            label = follower["species"].removeprefix("SPECIES_").lower()
            label += f" f{follower['form']}" if follower["form"] else ""
            label += " ♀" if follower["sex"] == "GENDER_FEMALE" else ""
            label += " shiny" if follower["shiny"] else ""
            groups.setdefault(group, []).append(label)
            if "map" in palette:
                mapped.add(group)
        own = sheet["group"] or (sheet["own"][0] if sheet["own"] else None)
        flags = []
        if "opt_out" in sheet["palette"]:
            flags.append("opt-out: " + sheet["palette"]["opt_out"])
            flagged["opt-out"].append(code)
        elif own:
            for group in groups:
                if group == own:
                    continue
                if group in mapped:
                    flags.append(f"mapped ({group})")
                    if code not in flagged["mapped"]:
                        flagged["mapped"].append(code)
                elif same_layout(own, group):
                    flags.append(f"forms ({group})")
                elif palettes_differ(own, group):
                    flags.append(f"other palette ({group})")
                    flagged["other palette"].append(code)
        uses = {}
        for use_code, kind, where in sheet["uses"]:
            uses.setdefault(kind, set()).add(where)
        use_text = "; ".join(f"{kind}: {', '.join(sorted(where))}" for kind, where in sorted(uses.items()))
        rows_text = "; ".join(f"{', '.join(sorted(set(labels)))}" for _, labels in groups.items())
        lines.append(f"| `{code.removeprefix('OBJ_CODE_').lower()}` | {own or '—'} | {rows_text or '—'} | "
                     f"{use_text or '—'} | {'; '.join(flags)} |")
    summary = [f"{len(sheets)} sheets: {sum(1 for c in sheets if c.startswith(FOLLOWER_PREFIX))} follower sheets, "
               f"{sum(1 for c in sheets if c.startswith(WALKING_PREFIX))} walking Pokémon; "
               f"{sum(len(s['rows']) for s in sheets.values())} follower rows; "
               f"{sum(1 for s in sheets.values() if s['uses'])} sheets shown by NPCs, scripts, ambients or the "
               f"Entralink run. "
               + "; ".join(f"{kind}: " + (", ".join("`" + c.removeprefix("OBJ_CODE_").lower() + "`" for c in codes)
                                          or "none") for kind, codes in flagged.items()) + ".", ""]
    output.write_text("\n".join(lines[:4] + summary + lines[4:]) + "\n")
    print(f"wrote {output}: {len(sheets)} sheets; " + ", ".join(f"{k} {len(v)}" for k, v in flagged.items()))


# ---------------------------------------------------------------- writing sheets

def write_json(path: Path, data: dict):
    sys.path.insert(0, str(ROOT))
    from tools.data.datajson import write
    write(path, data)


def battle_art(group: str, sexes: str) -> palette_remap.BattleArt:
    return palette_remap.BattleArt.load(POKEMON / group, art_directory(group), sexes)


def remap_sheet(path: Path, group: str, sexes: str = "m", dry_run: bool = False) -> list[str]:
    """Rewrites a sheet's sprite.png as GROUP's battle indices (F), with the battle normal palette as its PNG
    palette, removes sprite.pal and names the group in data.json. Returns the needs-a-look reasons."""
    sheet = palette_remap.Sheet.load(path / "sprite.png", path / "sprite.pal")
    art = battle_art(group, sexes)
    pixels, mapping = palette_remap.remap(sheet, art)
    reasons = palette_remap.report(sheet, art, mapping)
    if not dry_run:
        (path / "sprite.png").write_bytes(write_indexed_png(sheet.width, sheet.height, pixels, art.normal))
        (path / "sprite.pal").unlink()
        data = json.loads((path / "data.json").read_text())
        data["palette"] = {"pokemon": group}
        write_json(path / "data.json", data)
    return reasons


def row_map(sheet_path: Path, sheet_group: str, group: str, sexes: str = "m") -> list[int]:
    """For a follower row that shows another group's sheet (Appletun's on Budew's): the battle index of GROUP that
    each of the sheet's 16 indices plays, by E's colour map with the sheet's own colours (SHEET_GROUP's battle normal
    palette) standing for the follower colours. Index 0 stays 0; an index the sheet doesn't use goes to the nearest."""
    width, height, pixels, _ = read_indexed_png(sheet_path / "sprite.png")
    source = group_palettes(sheet_group)[0]
    sheet = palette_remap.Sheet(width, height, pixels, source)
    target = battle_art(group, sexes)
    mapping = palette_remap.colour_map(sheet.sprite, target)
    result = [0]
    for i in range(1, COLORS):
        if i in mapping:
            result.append(mapping[i])
        else:
            lab = palette_remap.oklab(source[i])
            result.append(min(palette_remap.candidates(target),
                              key=lambda t: palette_remap.delta(lab, target.normal_lab[t])))
    return result


def copied_palette(data: dict, group: str, own_sheet: bool) -> dict:
    """A follower's data.json copied for a new species or form (pokemon_species.py, pokemon_form.py), whose battle
    group GROUP starts as a copy of the template's palettes: a copied sheet of its own is on GROUP's palette (the same
    roles), and a row that shows another group's sheet keeps its map, or plays the sheet's indices one for one
    (identity), so that it keeps working when GROUP gets art and palettes of its own. An opt-out stays one."""
    palette = data.get("palette", {})
    if "opt_out" in palette:
        return data
    if own_sheet:
        if "pokemon" in palette:
            data["palette"] = {"pokemon": group}
    else:
        data["palette"] = {"pokemon": group, "map": palette.get("map", list(range(COLORS)))}
    return data


# ---------------------------------------------------------------- the build's side

def group_palettes(group: str) -> tuple[list, list]:
    return read_palette(POKEMON / group / "normal.pal"), read_palette(POKEMON / group / "shiny.pal")


def sheet_palette(data: dict, own_palette: Path) -> list:
    """The colours a sheet's texture set is written with: its group's battle normal palette, or its own sprite.pal
    when it opts out (or has no "palette")."""
    palette = data.get("palette", {})
    if "pokemon" in palette and "map" not in palette:
        return group_palettes(palette["pokemon"])[0]
    return read_palette(own_palette)


def row_palettes(row: dict, owner: dict) -> tuple[list, list] | None:
    """A follower row's normal and shiny colours (16 each), or None where it keeps its sheet's own (an opt-out, or
    a sheet that isn't on a battle palette). Raises ValueError where the row's group can't colour the sheet."""
    palette = row.get("palette", {})
    sheet = owner.get("palette", {})
    if "opt_out" in palette or "pokemon" not in sheet:
        return None
    follower = row["follower"]
    group = group_name(follower["species"], follower["form"])
    normal, shiny = group_palettes(palette.get("pokemon", group))
    if "map" in palette:
        index = palette["map"]
        return [normal[i] for i in index], [shiny[i] for i in index]
    if not same_layout(sheet["pokemon"], group):
        raise ValueError(f"{group}'s palette can't colour a sheet indexed on {sheet['pokemon']}: give the row a "
                         f"\"palette\" with a \"map\" (overworld_palettes.py) or an \"opt_out\"")
    return normal, shiny


PALETTE_MAGIC = b"FWCL"
PALETTE_VERSION = 1
NO_PALETTE = 0xFFFF


def palette_member(rows: list[tuple[int, tuple[list, list] | None]], code_base: int) -> bytes:
    """The followers' palettes member of the model table (FOLLOWING_PALETTES_FILE): "FWCL", version 1, the count of
    codes from code_base it covers, then a u16 a code (the index of its pair, 0xffff for none: its sheet's own colours),
    then the pairs, 32 bytes of normal colours and 32 of shiny (BGR555, index 0 transparent), each once."""
    count = max((code - code_base + 1 for code, _ in rows), default=0)
    index = [NO_PALETTE] * count
    pairs: list[bytes] = []
    for code, palettes in rows:
        if palettes is None:
            continue
        pair = palette_bytes(palettes[0]) + palette_bytes(palettes[1])
        if pair not in pairs:
            pairs.append(pair)
        index[code - code_base] = pairs.index(pair)
    header = PALETTE_MAGIC + struct.pack("<HH", PALETTE_VERSION, count)
    return header + b"".join(struct.pack("<H", i) for i in index) + b"".join(pairs)


def palette_bytes(colors: list) -> bytes:
    out = bytearray()
    for r, g, b in map(color5, colors):
        out += (r | g << 5 | b << 10).to_bytes(2, "little")
    return bytes(out)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "usage":
        write_usage(Path(sys.argv[2]))
    elif len(sys.argv) == 4 and sys.argv[1] == "remap":
        path, group = Path(sys.argv[2]), sys.argv[3]
        if not (POKEMON / group / "normal.pal").is_file():
            sys.exit(f"error: {group} is no battle group (res/pokemon/{group}/normal.pal)")
        reasons = remap_sheet(path, group, "f" if path.name.endswith("_female") and has_female_art(group) else "m")
        print(f"{path}: re-indexed onto {group}" + (f"; needs a look: {', '.join(reasons)}" if reasons else ""))
    elif len(sys.argv) >= 2 and sys.argv[1] == "convert":
        from tools.paperwhite2 import overworld_palettes_convert
        overworld_palettes_convert.convert(dry_run="--dry-run" in sys.argv)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
