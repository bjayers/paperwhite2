#!/usr/bin/env python3
"""Paper White 2's trainer level scaling: the generated header of res/paperwhite2/trainer_scaling/trainer_scaling.json.

    trainer_scaling.py SOURCE_JSON OUTPUT_HEADER        # paperwhite2/trainer_scaling_config.h
    trainer_scaling.py preview TRAINER PARTY_LEVEL [BADGES]   # a trainer's party scaled, as the game scales it

The file (its schema beside it) has the tiers, each a team's levels from the player's party level: the ace at the
party level + top, the others keeping their original gap below the ace but no lower than the party level + bottom, and
whether a Pokémon may go below its original level. Each class has a tier (the default one unless listed), a trainer
may have another, and "fixed" means not scaled; a partner on the player's side takes ally_tier. badge_floor is the
least party level for each badge count. src/paperwhite2/main/paperwhite2_trainer_scaling.c reads the header
(docs/paperwhite2/plugins.md, Trainer scaling). Only the hack's build runs this (configure.py --hack).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.data import datajson  # noqa: E402
from tools.data.gen_constants import load as load_list  # noqa: E402

SOURCE = ROOT / "res" / "paperwhite2" / "trainer_scaling" / "trainer_scaling.json"
GUARD = "POKEBW2_PAPERWHITE2_TRAINER_SCALING_CONFIG_H"
FIXED = "fixed"
FIXED_INDEX = 0xFF
LEVEL_LOWEST, LEVEL_HIGHEST = 1, 100


class DataError(Exception):
    pass


def load(path: Path = SOURCE) -> dict:
    data = datajson.load(path, datajson.load_schema(path.parent / "trainer_scaling.schema.json"))
    names = [tier["name"] for tier in data["tiers"]]
    if FIXED in names:
        raise DataError(f"{path}: a tier can't be named {FIXED!r}, which means not scaled")
    if len(set(names)) != len(names):
        raise DataError(f"{path}: two tiers have the same name")
    for tier in data["tiers"]:
        if tier["bottom"] > tier["top"]:
            raise DataError(f"{path}: tier {tier['name']!r}'s bottom is above its top")
    for key in ("default_tier", "ally_tier"):
        if data[key] not in names:
            raise DataError(f"{path}: {key} {data[key]!r} is not a tier")
    return data


def tier_index(data: dict, name: str, where: str) -> int:
    if name == FIXED:
        return FIXED_INDEX
    names = [tier["name"] for tier in data["tiers"]]
    if name not in names:
        raise DataError(f"{where}: tier {name!r} is not a tier or {FIXED!r}")
    return names.index(name)


def class_tiers(data: dict) -> list[int]:
    classes = load_list("trainer_classes")
    tiers = [tier_index(data, data["default_tier"], "default_tier")] * (max(classes.values()) + 1)
    seen = set()
    for entry in data["classes"]:
        if entry["class"] not in classes:
            raise DataError(f"classes: {entry['class']} is not in generated/trainer_classes.txt")
        if entry["class"] in seen:
            raise DataError(f"classes: {entry['class']} is listed twice")
        seen.add(entry["class"])
        tiers[classes[entry["class"]]] = tier_index(data, entry["tier"], f"classes: {entry['class']}")
    return tiers


def trainer_tiers(data: dict) -> list[tuple[int, int]]:
    trainers = load_list("trainers")
    rows = {}
    for entry in data["trainers"]:
        if entry["trainer"] not in trainers:
            raise DataError(f"trainers: {entry['trainer']} is not in generated/trainers.txt")
        number = trainers[entry["trainer"]]
        if number in rows:
            raise DataError(f"trainers: {entry['trainer']} is listed twice")
        rows[number] = tier_index(data, entry["tier"], f"trainers: {entry['trainer']}")
    return sorted(rows.items())


def header(path: Path) -> str:
    data = load(path)
    tiers = class_tiers(data)
    trainers = trainer_tiers(data)
    lines = [
        f"#ifndef {GUARD}", f"#define {GUARD}", "",
        f"// Generated by tools/paperwhite2/trainer_scaling.py from {path.resolve().relative_to(ROOT).as_posix()}, edit",
        "// that instead (docs/paperwhite2/plugins.md, Trainer scaling)", "",
        f"#define TRAINER_SCALING_TIER_FIXED {FIXED_INDEX:#04x}",
        f"#define TRAINER_SCALING_TIER_COUNT {len(data['tiers'])}",
        "// Each tier: the ace's level and the lowest from the party's level, and whether below the original level",
        "#define TRAINER_SCALING_TIERS \\",
        *(f"    {{ {t['top']}, {t['bottom']}, {'TRUE' if t['below_original'] else 'FALSE'} }}, /* {t['name']} */ \\"
          for t in data["tiers"]),
        "",
        f"#define TRAINER_SCALING_ALLY_TIER {tier_index(data, data['ally_tier'], 'ally_tier')}",
        "// Each class's tier, by its number",
        f"#define TRAINER_SCALING_CLASS_COUNT {len(tiers)}",
        "#define TRAINER_SCALING_CLASS_TIERS \\",
        *(f"    {', '.join(f'{t:#04x}' for t in tiers[i:i + 16])}, \\" for i in range(0, len(tiers), 16)),
        "",
        "// The trainers whose tier isn't their class's, by trainer ID, sorted",
        f"#define TRAINER_SCALING_TRAINER_COUNT {len(trainers)}",
        "#define TRAINER_SCALING_TRAINERS \\",
        *(f"    {{ {number}, {tier:#04x} }}, \\" for number, tier in trainers),
        "",
        "// The least party level for 0 to 8 badges",
        "#define TRAINER_SCALING_BADGE_FLOOR \\",
        f"    {', '.join(str(level) for level in data['badge_floor'])}",
        "", f"#endif // {GUARD}", "",
    ]
    return "\n".join(lines)


def scale(levels: list[int], tier: dict, party_level: int) -> list[int]:
    """A team's levels scaled as PaperWhite2_TrainerScaling_Apply scales them."""
    ace = max(levels)
    top = min(LEVEL_HIGHEST, max(LEVEL_LOWEST, party_level + tier["top"]))
    bottom = min(LEVEL_HIGHEST, max(LEVEL_LOWEST, party_level + tier["bottom"]))
    out = []
    for level in levels:
        new = max(top - (ace - level), bottom)
        if not tier["below_original"]:
            new = max(new, level)
        out.append(min(LEVEL_HIGHEST, max(LEVEL_LOWEST, new)))
    return out


def preview(trainer: str, party_level: int, badges: int):
    data = load()
    trainers = load_list("trainers")
    if trainer not in trainers:
        raise DataError(f"{trainer} is not in generated/trainers.txt")
    record = json.loads((ROOT / "res" / "trainers" / "data" / f"{trainer.removeprefix('TRAINER_').lower()}.json").read_text())
    overrides = dict(trainer_tiers(data))
    classes = load_list("trainer_classes")
    tier = overrides.get(trainers[trainer], class_tiers(data)[classes[record["class"]]])
    levels = [member["level"] for member in record["party"]]
    if tier == FIXED_INDEX:
        print(f"{trainer} ({record['class']}): fixed, {levels}")
        return
    basis = max(party_level, data["badge_floor"][min(badges, 8)])
    print(f"{trainer} ({record['class']}, {data['tiers'][tier]['name']}), party level {basis}: {levels} -> "
          f"{scale(levels, data['tiers'][tier], basis)}, before the difficulty")


def write_if_changed(path: Path, text: str):
    if not path.exists() or path.read_text() != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "preview":
        parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
        parser.add_argument("command")
        parser.add_argument("trainer")
        parser.add_argument("party_level", type=int)
        parser.add_argument("badges", type=int, nargs="?", default=8)
        args = parser.parse_args()
        try:
            preview(args.trainer, args.party_level, args.badges)
        except DataError as error:
            sys.exit(f"error: {error}")
        return
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        write_if_changed(args.output, header(args.source))
    except DataError as error:
        sys.exit(f"error: {error}")


if __name__ == "__main__":
    main()
